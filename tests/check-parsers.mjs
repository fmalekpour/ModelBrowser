import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {DOMParser} from 'linkedom';
import {STLLoader} from '../node_modules/three/examples/jsm/loaders/STLLoader.js';
import {ThreeMFLoader} from '../node_modules/three/examples/jsm/loaders/3MFLoader.js';
import {Box3,Vector3} from '../node_modules/three/build/three.module.js';
globalThis.DOMParser=DOMParser;
const buffer=async name=>{const b=await fs.readFile(new URL('../.test-work/fixtures/'+name,import.meta.url));return b.buffer.slice(b.byteOffset,b.byteOffset+b.byteLength);};
const stl=new STLLoader().parse(await buffer('Tetrahedron.stl'));
assert.equal(stl.attributes.position.count,12);stl.computeBoundingBox();
assert.deepEqual(stl.boundingBox.getSize(new Vector3()).toArray(),[30,24,40]);
const binary=new ArrayBuffer(134),view=new DataView(binary);view.setUint32(80,1,true);
const values=[0,0,1,0,0,0,10,0,0,0,10,0];values.forEach((v,i)=>view.setFloat32(84+i*4,v,true));
assert.equal(new STLLoader().parse(binary).attributes.position.count,3);
const model=new ThreeMFLoader().parse(await buffer('Tetrahedron.3mf'));
let triangles=0;model.traverse(o=>{if(o.isMesh)triangles+=(o.geometry.index?.count??o.geometry.attributes.position.count)/3;});
assert.equal(triangles,4);
assert.deepEqual(new Box3().setFromObject(model).getSize(new Vector3()).toArray(),[30,24,40]);
console.log('PASS: ASCII STL, binary STL, 3MF ZIP import, triangle counts, model dimensions.');
